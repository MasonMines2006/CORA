/*
 * Where the student is in the app, kept in the URL query string
 * (/student?view=lesson&concept=Reactivity&beat=2).
 *
 * Tabs used to live only in React state, so a refresh dropped you on Home and
 * the back button left the app. The query string fixes both and makes any
 * screen linkable, without turning views into routes. Routes would unmount
 * Ask and lose the conversation, which is why the app avoids them.
 *
 * The redesign (docs/redesign/DESIGN.md section 3.4) replaced the old
 * home / concepts / graph / review / ask views with the ones below. Old links
 * are translated rather than dropped, so a bookmarked concept page still opens.
 */

export type StudentView = 'path' | 'ask' | 'lesson' | 'quiz' | 'results' | 'review' | 'progress' | 'graph';

const VIEWS: readonly StudentView[] = ['path', 'ask', 'lesson', 'quiz', 'results', 'review', 'progress', 'graph'];

/** Lessons, quizzes and results take the whole screen: no sidebar, no tab bar. */
const FOCUS_VIEWS: readonly StudentView[] = ['lesson', 'quiz', 'results'];

/** Views that work on one concept, so `&concept=` belongs in their URL. */
const CONCEPT_VIEWS: readonly StudentView[] = ['ask', 'lesson', 'quiz', 'results', 'review', 'graph'];

export interface StudentLocation {
  view: StudentView;
  /** The concept this view is about. Empty when it is about the whole course. */
  conceptId: string;
  /** Lesson step to open at. Only meaningful for `lesson`. */
  beat?: number;
  /** Which saved Ask conversation is open. Only meaningful for `ask`. */
  session?: string;
}

/** Lessons have four steps; anything outside a small range is a bad link, not a position. */
const MAX_BEAT = 9;

/** Session ids are generated by this app ("s-" plus a few letters and digits). */
const SESSION_ID = /^[a-z0-9-]{1,64}$/i;

const isView = (value: string | null): value is StudentView => VIEWS.includes(value as StudentView);

export const isFocusView = (view: StudentView): boolean => FOCUS_VIEWS.includes(view);

const parseBeat = (value: string | null): number | undefined => {
  if (value === null || !/^\d+$/.test(value)) {
    return undefined;
  }
  const beat = Number(value);
  return beat <= MAX_BEAT ? beat : undefined;
};

const parseSession = (value: string | null): string | undefined => {
  return value !== null && SESSION_ID.test(value) ? value : undefined;
};

/**
 * Before the redesign a concept page was `view=concepts&concept=X&mode=...`.
 * Its Practice tab is now the quiz; every other tab is now the lesson.
 */
const legacyView = (view: string | null, conceptId: string, mode: string | null): StudentView => {
  if (view === 'concepts' && conceptId) {
    return mode === 'practice' ? 'quiz' : 'lesson';
  }
  return 'path';
};

/** The URL is user input: anything unrecognised falls back to a safe default. */
export const parseLocation = (params: URLSearchParams): StudentLocation => {
  const rawView = params.get('view');
  const conceptId = params.get('concept') ?? '';
  return {
    view: isView(rawView) ? rawView : legacyView(rawView, conceptId, params.get('mode')),
    conceptId,
    beat: parseBeat(params.get('beat')),
    session: parseSession(params.get('session')),
  };
};

export const toSearchParams = (location: StudentLocation): URLSearchParams => {
  const params = new URLSearchParams();
  if (location.view === 'path') {
    return params;
  }
  params.set('view', location.view);
  if (CONCEPT_VIEWS.includes(location.view) && location.conceptId) {
    params.set('concept', location.conceptId);
  }
  if (location.view === 'lesson' && location.beat !== undefined) {
    params.set('beat', String(location.beat));
  }
  if (location.view === 'ask' && location.session) {
    params.set('session', location.session);
  }
  return params;
};
