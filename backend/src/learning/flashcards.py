"""Build review cards from a cached lesson and order them into a queue.

Pure functions: the caller loads the lesson and the learner's schedules.

Cards are never generated by the LLM. A concept has cards only once its lesson
is cached, and each card is one lesson beat -- so review always matches what
the student read. The prompts mirror `lessonCards()` in
frontend/src/components/Student/StudentStudyTools.tsx.
"""

from dataclasses import dataclass
from datetime import datetime
from typing import Optional

from src.learning.models import GeneratedLesson
from src.learning.review import CardState, card_status, preview_intervals
from src.learning.review_models import ReviewCard, ReviewIntervals, ReviewQueue

CARD_KEYS: tuple[str, ...] = ("core_idea", "how_it_works", "pulstar_application", "quick_check")
CARD_ID_SEPARATOR = "::"
FALLBACK_SOURCE = "Course material"


@dataclass(frozen=True)
class Flashcard:
    card_id: str
    concept_id: str
    key: str
    prompt: str
    answer: str
    source: str


@dataclass(frozen=True)
class ConceptCards:
    """Every card one concept's cached lesson yields."""

    concept_id: str
    concept_name: str
    cards: tuple[Flashcard, ...]


def make_card_id(concept_id: str, key: str) -> str:
    return f"{concept_id}{CARD_ID_SEPARATOR}{key}"


def parse_card_id(card_id: str) -> Optional[tuple[str, str]]:
    """Split a card id into (concept_id, key), or None if it is not a card id."""
    # Split on the LAST separator: a key never contains it, but a concept id might.
    concept_id, separator, key = card_id.rpartition(CARD_ID_SEPARATOR)
    if not separator or not concept_id or key not in CARD_KEYS:
        return None
    return concept_id, key


def _quick_check_answer(lesson: GeneratedLesson) -> str:
    check = lesson.quick_check
    if 0 <= check.answer_index < len(check.options):
        return f"{check.options[check.answer_index]}. {check.explanation}"
    # A malformed generation must not crash review; the explanation still teaches.
    return check.explanation


def build_cards(
    concept_id: str,
    concept_name: str,
    lesson: GeneratedLesson,
    sources: list[str],
) -> list[Flashcard]:
    """Turn one cached lesson into its review cards, in beat order."""
    first_source = sources[0] if sources else FALLBACK_SOURCE
    pulstar_source = next(
        (source for source in sources if "pulstar" in source.lower()), first_source
    )
    content = {
        "core_idea": (f"What is the core idea behind {concept_name}?", lesson.core_idea, first_source),
        "how_it_works": (f"How does {concept_name} work?", lesson.how_it_works, first_source),
        "pulstar_application": (
            f"How is {concept_name} used at PULSTAR?",
            lesson.pulstar_application,
            pulstar_source,
        ),
        "quick_check": (lesson.quick_check.question, _quick_check_answer(lesson), first_source),
    }
    return [
        Flashcard(
            card_id=make_card_id(concept_id, key),
            concept_id=concept_id,
            key=key,
            prompt=prompt,
            answer=answer,
            source=source,
        )
        for key, (prompt, answer, source) in content.items()
        # A card with a blank back is useless; the frontend dropped these too.
        if answer.strip()
    ]


def _review_card(concept: ConceptCards, card: Flashcard, state: Optional[CardState], now: datetime) -> ReviewCard:
    return ReviewCard(
        card_id=card.card_id,
        concept_id=card.concept_id,
        concept_name=concept.concept_name,
        prompt=card.prompt,
        answer=card.answer,
        source=card.source,
        state=card_status(state),
        last_reviewed_at=state.last_reviewed_at if state else None,
        due_at=state.due_at if state else None,
        intervals=ReviewIntervals(**preview_intervals(state or CardState(), now)),
    )


def build_queue(
    concepts: list[ConceptCards],
    states: dict[str, CardState],
    now: datetime,
    limit: int,
    new_limit: int,
) -> ReviewQueue:
    """Due cards first (oldest due first), then never-graded cards.

    `concepts` is in priority order: new cards are taken concept by concept.
    Schedules for cards not in `concepts` are ignored -- if a lesson is no
    longer cached, its cards cannot be shown, so they are not counted either.
    """
    due: list[tuple[datetime, ReviewCard]] = []
    new: list[ReviewCard] = []
    for concept in concepts:
        for card in concept.cards:
            state = states.get(card.card_id)
            if card_status(state) == "new":
                new.append(_review_card(concept, card, None, now))
            elif state.due_at is not None and state.due_at <= now:
                due.append((state.due_at, _review_card(concept, card, state, now)))

    # sorted() is stable, so equal due times keep concept and beat order.
    due_cards = [card for _, card in sorted(due, key=lambda item: item[0])]
    selected = due_cards[:limit]
    new_slots = max(0, min(new_limit, limit - len(selected)))
    return ReviewQueue(
        due_count=len(due_cards),
        new_count=len(new),
        cards=selected + new[:new_slots],
    )
